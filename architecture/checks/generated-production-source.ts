import { readRuntimeIndexSnapshotFile as readIndexSnapshotFile } from "../tooling/runtime/projection-custody.ts";
import { constants, type BigIntStats } from "node:fs";
import type { FileHandle } from "node:fs/promises";
import { lstat, open, realpath } from "node:fs/promises";
import { resolve, sep } from "node:path";
import {
  assertGitIndexSnapshotCurrent, type GitIndexSnapshot,
} from "./tracked-file-custody.ts";

export type GeneratedProductionReader = (path: string) => Promise<Buffer>;

export const GENERATED_PRODUCTION_PATH =
  "packages/core/src/composition/generated/stage1.ts";

function fail(message: string): never {
  throw new Error(`GENERATED_PRODUCTION_SOURCE_FAILED: ${message}`);
}

function sameIdentity(left: BigIntStats, right: BigIntStats): boolean {
  const keys = ["dev", "ino", "mode", "size", "mtimeNs", "ctimeNs"] as const;
  return keys
    .every(key => left[key] === right[key]);
}

async function observe(repositoryRoot: string) {
  const root = resolve(repositoryRoot);
  const rootStatus = await lstat(root, { bigint: true });
  if (!rootStatus.isDirectory() || rootStatus.isSymbolicLink()) fail("invalid repository root");
  const observations = [rootStatus];
  let path = root;
  let leaf = rootStatus;
  const parts = GENERATED_PRODUCTION_PATH.split("/");
  for (const [index, part] of parts.entries()) {
    path = resolve(path, part);
    const status = await lstat(path, { bigint: true });
    if (status.isSymbolicLink()
      || (index === parts.length - 1 ? !status.isFile() : !status.isDirectory())) {
      fail("generated path must contain only directories and a regular file");
    }
    observations.push(status);
    leaf = status;
  }
  const rootRealPath = await realpath(root);
  if (!(await realpath(path)).startsWith(`${rootRealPath}${sep}`)) {
    fail("generated source escapes the repository");
  }
  return { path, observations, leaf };
}

// Expected bytes originate in the fresh emitter call, never in the candidate.
// Copy both at construction and return so callers cannot mutate that expectation.
export function createGeneratedProductionReader(repositoryRoot: string, expectedBytes: Buffer): GeneratedProductionReader {
  if (!Buffer.isBuffer(expectedBytes)) throw new TypeError("expected bytes must be a Buffer");
  const expected = Buffer.from(expectedBytes);
  return async path => {
    if (path !== GENERATED_PRODUCTION_PATH) fail("path is not the generated production root");
    const before = await observe(repositoryRoot);
    let handle: FileHandle | undefined;
    try {
      handle = await open(before.path,
        constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
      const opened = await handle.stat({ bigint: true });
      if (!opened.isFile() || !sameIdentity(before.leaf, opened)) {
        fail("pathname changed before opening");
      }
      const bytes = await handle.readFile();
      const finished = await handle.stat({ bigint: true });
      const after = await observe(repositoryRoot);
      if (!sameIdentity(opened, finished)
        || !sameIdentity(finished, after.leaf)
        || before.observations.some((status, index) => {
          const observed = after.observations[index];
          return observed === undefined || !sameIdentity(status, observed);
        })) {
        fail("pathname or file changed during reading");
      }
      if (!bytes.equals(expected)) fail("generated bytes differ from fresh emission");
      return Buffer.from(bytes);
    } finally {
      await handle?.close();
    }
  };
}

// Discovery is supplied by the generator's finite input inventory. This helper
// grants no admission: governance obtains its reader only from its own build.
export async function verifySnapshotInputs(snapshot: GitIndexSnapshot, paths: readonly string[]): Promise<void> {
  await assertGitIndexSnapshotCurrent(snapshot);
  if (snapshot.entries.has(GENERATED_PRODUCTION_PATH)) {
    fail("generated production source must not have an index entry");
  }
  for (const path of paths) {
    await readIndexSnapshotFile(snapshot, path, "generation input");
  }
  await assertGitIndexSnapshotCurrent(snapshot);
}
